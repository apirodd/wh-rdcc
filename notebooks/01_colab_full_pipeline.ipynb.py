    "def estimate_wiener_hopf(z_seq, eps=1e-4):\n",
    "    \"\"\"Stima closed-form di W* risolvendo equazione di Wiener-Hopf.\"\"\"\n",
    "    B, L, d = z_seq.shape\n",
    "    z_t = z_seq[:, :-1, :].reshape(-1, d)\n",
    "    z_tp1 = z_seq[:, 1:, :].reshape(-1, d)\n",
    "    \n",
    "    N = z_t.shape[0]\n",
    "    Rzz0 = (z_t.T @ z_t) / N\n",
