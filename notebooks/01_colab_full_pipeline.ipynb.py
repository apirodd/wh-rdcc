    "def load_calibrate(tfrecords_path, offsets_path):\n",
    "    \"\"\"Crea un dataset TFRecord calibrato e riordinato per antenne.\"\"\"\n",
    "    with open(offsets_path) as f:\n",
    "        offsets = json.load(f)\n",
    "    \n",
    "    def parse(proto):\n",
    "        record = tf.io.parse_single_example(proto, {\n",
    "            \"csi\": tf.io.FixedLenFeature([], tf.string, default_value=\"\"),\n",
    "            \"pos-tachy\": tf.io.FixedLenFeature([], tf.string, default_value=\"\"),\n",
    "            \"time\": tf.io.FixedLenFeature([], tf.float32, default_value=0),\n",
    "        })\n",
    "        csi = tf.ensure_shape(\n",
    "            tf.io.parse_tensor(record[\"csi\"], out_type=tf.float32),\n",
    "            (antenna_count, 1024, 2))\n",
    "        csi = tf.complex(csi[:,:,0], csi[:,:,1])\n",
    "        csi = tf.signal.fftshift(csi, axes=1)\n",
    "        pos = tf.ensure_shape(\n",
    "            tf.io.parse_tensor(record[\"pos-tachy\"], out_type=tf.float64), (3,))\n",
    "        return csi, pos, record[\"time\"]\n",
    "    \n",
    "    def calibrate(csi, pos, time):\n",
    "        sto = tf.tensordot(tf.constant(offsets[\"sto\"]),\n",
    "            2*np.pi*tf.range(tf.shape(csi)[1], dtype=tf.float32)/\n",
    "            tf.cast(tf.shape(csi)[1], tf.float32), axes=0)\n",
    "        cpo = tf.tensordot(tf.constant(offsets[\"cpo\"]),\n",
    "            tf.ones(tf.shape(csi)[1], dtype=tf.float32), axes=0)\n",
    "        csi = tf.multiply(csi, tf.exp(tf.complex(0.0, sto+cpo)))\n",
    "        return csi, pos, time\n",
    "    \n",
    "    def reorder(csi, pos, time):\n",
    "        csi = tf.stack([[tf.gather(csi, idx) for idx in arr]\n",
    "                        for arr in antenna_assignments])\n",
    "        return csi, pos, time\n",
    "    \n",
    "    ds = tf.data.TFRecordDataset(tfrecords_path)\n",
    "    ds = ds.map(parse, num_parallel_calls=tf.data.AUTOTUNE)\n",
    "    ds = ds.map(calibrate, num_parallel_calls=tf.data.AUTOTUNE)\n",
    "    ds = ds.map(reorder, num_parallel_calls=tf.data.AUTOTUNE)\n",
    "    return ds"
